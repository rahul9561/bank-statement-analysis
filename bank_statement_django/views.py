"""REST endpoints.

POST /analyze/                      upload a statement (multipart field ``statement``)
GET  /analyses/                     list the caller's analyses
GET  /analyses/<report_id>/         JSON result (owner or authorised staff)
GET  /reports/<report_id>/          download the PDF report (owner or authorised staff)
DELETE /analyses/<report_id>/       delete an analysis and its report

Errors never include stack traces, file paths or statement content.
"""

from __future__ import annotations

import logging

from django.http import FileResponse, Http404
from rest_framework import status
from rest_framework.parsers import FormParser, MultiPartParser
from rest_framework.permissions import IsAuthenticated
from rest_framework.response import Response
from rest_framework.throttling import ScopedRateThrottle
from rest_framework.views import APIView

from bank_statement_engine import BankStatementError

from . import conf, services
from .models import StatementAnalysis
from .permissions import IsOwnerOrStaff
from .serializers import StatementAnalysisSerializer, StatementUploadSerializer
from .validators import read_validated_upload

logger = logging.getLogger("bank_statement_django")


def error_response(code: str, message: str, http_status: int, details: dict | None = None) -> Response:
    return Response({"success": False, "status": "failed", "error": {"code": code, "message": message,
                                                                      "details": details or {}}},
                    status=http_status)


class AnalyzeStatementView(APIView):
    permission_classes = [IsAuthenticated]
    parser_classes = [MultiPartParser, FormParser]
    throttle_classes = [ScopedRateThrottle]
    throttle_scope = conf.DEFAULTS["THROTTLE_SCOPE"]

    def get_throttles(self):
        self.throttle_scope = conf.get("THROTTLE_SCOPE")
        return super().get_throttles()

    def post(self, request):
        serializer = StatementUploadSerializer(data=request.data)
        if not serializer.is_valid():
            # Field errors are generated by DRF and contain no file content.
            return error_response("INVALID_REQUEST", "The upload request is invalid.", 400,
                                  {"fields": serializer.errors})
        params = serializer.validated_data
        try:
            data = read_validated_upload(params["statement"])
            holder = params.get("holder_name") or ""
            record = services.analyze_statement(
                request.user, data,
                password=params.get("password") or None,
                holder_names=[holder] if holder.strip() else None,
            )
        except BankStatementError as exc:
            logger.info("Statement rejected for user=%s code=%s", request.user.pk, exc.code)
            return error_response(exc.code, exc.safe_message, exc.http_status, exc.details)
        except Exception:
            logger.exception("Unexpected failure analysing a statement for user=%s", request.user.pk)
            return error_response("INTERNAL_ERROR", "The statement could not be processed. Please try again later.", 500)

        body = StatementAnalysisSerializer(record).data
        result = record._engine_result
        payload = {
            "success": True,
            "status": record.status,
            **body,
            "risk_indicators": [{"code": r.code, "severity": r.severity, "title": r.title}
                                for r in result.risk_indicators],
        }
        if params.get("include_transactions") and conf.get("INCLUDE_TRANSACTIONS_IN_RESPONSE"):
            payload["transactions"] = [t.to_dict() for t in result.transactions]
        return Response(payload, status=status.HTTP_201_CREATED)


class _OwnedAnalysisMixin:
    permission_classes = [IsAuthenticated, IsOwnerOrStaff]

    def get_object(self, request, report_id: str) -> StatementAnalysis:
        try:
            obj = StatementAnalysis.objects.get(report_id=report_id)
        except StatementAnalysis.DoesNotExist:
            raise Http404
        # Use 404 rather than 403 for other users' reports so report IDs cannot be probed.
        if not IsOwnerOrStaff().has_object_permission(request, self, obj):
            raise Http404
        if obj.is_expired:
            raise Http404
        return obj


class AnalysisListView(APIView):
    permission_classes = [IsAuthenticated]

    def get(self, request):
        qs = StatementAnalysis.objects.filter(owner=request.user)[:100]
        return Response({"results": StatementAnalysisSerializer(qs, many=True).data})


class AnalysisDetailView(_OwnedAnalysisMixin, APIView):
    def get(self, request, report_id: str):
        obj = self.get_object(request, report_id)
        data = StatementAnalysisSerializer(obj).data
        data["result"] = obj.result
        return Response(data)

    def delete(self, request, report_id: str):
        obj = self.get_object(request, report_id)
        services.delete_analysis(obj)
        return Response(status=status.HTTP_204_NO_CONTENT)


class ReportDownloadView(_OwnedAnalysisMixin, APIView):
    def get(self, request, report_id: str):
        obj = self.get_object(request, report_id)
        if not obj.report_file:
            raise Http404
        try:
            path = services.safe_report_path(obj.report_file)
        except PermissionError:
            logger.error("Stored report path rejected for %s", obj.report_id)
            raise Http404
        if not path.is_file():
            raise Http404
        response = FileResponse(path.open("rb"), content_type="application/pdf", as_attachment=True,
                                filename=f"{obj.report_id}.pdf")
        response["Cache-Control"] = "private, no-store"
        response["X-Content-Type-Options"] = "nosniff"
        return response
